/** Required Kv for liquid flow, Q in m³/h, Δp in bar. */
export function requiredKv(flowM3H, densityKgM3, dpBar) {
  return flowM3H * Math.sqrt(densityKgM3 / 1000 / dpBar);
}

/**
 * @param {object} rawInputs values in schema units; missing keys take the schema defaults
 * @returns {{ outputs: object, warnings: string[] }}
 */
export function calculate(rawInputs) {
  const i = withDefaults(schema, rawInputs);
  assertPositive(i.flow_m3_h, 'flow_m3_h', 'Flow');
  assertPositive(i.density_kg_m3, 'density_kg_m3', 'Density');
  assertPositive(i.p1_bar_a, 'p1_bar_a', 'Inlet pressure');
  assertPositive(i.p2_bar_a, 'p2_bar_a', 'Outlet pressure');
  if (i.p2_bar_a >= i.p1_bar_a) throw new Error('Outlet pressure must be below the inlet pressure');
  assertNonNegative(i.pv_bar_a, 'pv_bar_a', 'Vapour pressure');
  assertPositive(i.pc_bar_a, 'pc_bar_a', 'Critical pressure');
  if (i.pv_bar_a >= i.p1_bar_a) throw new Error('Vapour pressure at or above the inlet pressure: the liquid flashes at the inlet');
  assertOneOf(i.valve_type, Object.keys(VALVE_TYPES), 'valve_type', 'Valve type');
  assertNonNegative(i.rated_kv, 'rated_kv', 'Rated Kv');
  assertPositive(i.pipe_diameter_mm, 'pipe_diameter_mm', 'Pipe diameter');

  const fl = i.valve_type === 'custom' ? assertRange(i.fl_custom, 0.2, 1, 'fl_custom', 'F_L') : VALVE_TYPES[i.valve_type].fl;
  const dp = i.p1_bar_a - i.p2_bar_a;
  const ff = 0.96 - 0.28 * Math.sqrt(i.pv_bar_a / i.pc_bar_a);
  const dpMax = fl * fl * (i.p1_bar_a - ff * i.pv_bar_a);
  const choked = dp >= dpMax;
  const dpSizing = Math.min(dp, dpMax);
  const kv = requiredKv(i.flow_m3_h, i.density_kg_m3, dpSizing);
  const cv = kv * CV_PER_KV;
  const ratio = dp / (i.p1_bar_a - i.pv_bar_a);
  const opening = i.rated_kv > 0 ? (kv / i.rated_kv) * 100 : null;
  const velocity = (i.flow_m3_h / 3600) / (Math.PI * (i.pipe_diameter_mm / 2000) ** 2);
  const maxFlow = i.rated_kv > 0 ? i.rated_kv * Math.sqrt(dpMax / (i.density_kg_m3 / 1000)) : null;
  const incipient = !choked && dp > 0.7 * dpMax;

  let openingCheck;
  if (opening === null) openingCheck = 'No valve selected yet: choose a rated Kv about 1.3–1.6 × the required value so maximum flow sits at 60–80 % opening';
  else if (opening > 90) openingCheck = `UNDERSIZED — ${opening.toFixed(0)} % of the rated Kv: no margin, choose the next size`;
  else if (opening > 80) openingCheck = `Marginal — ${opening.toFixed(0)} % of the rated Kv at this flow (aim for 60–80 % at maximum flow)`;
  else if (opening < 20) openingCheck = `OVERSIZED — ${opening.toFixed(0)} % of the rated Kv: poor control near the seat, choose a smaller valve or reduced trim`;
  else openingCheck = `OK — ${opening.toFixed(0)} % of the rated Kv`;

  const warnings = [];
  if (choked) warnings.push(`Choked flow: the pressure drop ${dp.toFixed(2)} bar exceeds Δp_max ${dpMax.toFixed(2)} bar — the flow cannot increase with a larger drop and the valve is sized on Δp_max; expect cavitation damage and noise unless anti-cavitation trim is used.`);
  else if (incipient) warnings.push(`Pressure drop above 70 % of the choked limit: incipient cavitation likely (σ margin small) — check the manufacturer's cavitation index for the trim.`);
  if (velocity > 4) warnings.push(`Pipe velocity ${velocity.toFixed(1)} m/s above 4 m/s: erosion and noise risk at the valve outlet — consider a larger pipe.`);
  if (i.density_kg_m3 > 1300 || i.density_kg_m3 < 600) warnings.push('Density far from water: check that the fluid is a single-phase Newtonian liquid (viscous fluids need the Reynolds factor F_R).');
  warnings.push('F_P = 1 (line-size valve) and turbulent flow assumed; reducers, viscous liquids, flashing (p₂ < p_v) and gas/steam service need the full IEC 60534-2-1 procedure.');
  warnings.push('Typical F_L values: the manufacturer\'s value for the selected trim and opening governs the choked-flow limit.');

  return {
    outputs: {
      dp_actual_bar: dp,
      ff,
      fl,
      dp_max_bar: dpMax,
      dp_sizing_bar: dpSizing,
      flow_regime: choked ? `CHOKED — Δp ${dp.toFixed(2)} bar ≥ Δp_max ${dpMax.toFixed(2)} bar` : incipient ? `Turbulent, near cavitation — Δp is ${((dp / dpMax) * 100).toFixed(0)} % of Δp_max` : `Turbulent, non-cavitating — Δp is ${((dp / dpMax) * 100).toFixed(0)} % of Δp_max`,
      kv,
      cv,
      opening_pct: opening,
      opening_check: openingCheck,
      cavitation_ratio: ratio,
      pipe_velocity_m_s: velocity,
      max_flow_choked_m3_h: maxFlow,
    },
    warnings,
  };
}
